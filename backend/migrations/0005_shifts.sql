CREATE TABLE shift_calendar (
    company_id BIGINT NOT NULL REFERENCES companies(id),
    work_date TEXT NOT NULL,
    day_type TEXT NOT NULL CHECK (day_type IN ('holiday', 'working')),
    label TEXT NOT NULL,
    PRIMARY KEY (company_id, work_date)
);

CREATE TABLE shifts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    work_date TEXT NOT NULL,
    starts_at TEXT NOT NULL,
    ends_at TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('normal', 'duty')),
    decision TEXT CHECK (decision IN ('continue', 'pause', 'transfer', 'finish')),
    decided_at TEXT,
    finished_at TEXT,
    transfer_task_id BIGINT REFERENCES tasks(id)
);

CREATE INDEX shifts_by_company_time ON shifts(company_id, starts_at);
CREATE INDEX shifts_by_employee_time ON shifts(company_id, employee_id, starts_at, ends_at);

CREATE TABLE shift_task_actions (
    shift_id BIGINT NOT NULL REFERENCES shifts(id),
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    decision TEXT NOT NULL CHECK (decision IN ('pause', 'transfer')),
    requested_at TEXT NOT NULL,
    transferred_at TEXT,
    PRIMARY KEY (shift_id, task_id)
);

CREATE TABLE unavailable_employees (
    company_id BIGINT NOT NULL REFERENCES companies(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    unavailable_since TEXT NOT NULL,
    PRIMARY KEY (company_id, employee_id)
);
