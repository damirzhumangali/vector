CREATE TABLE work_trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    created_by BIGINT NOT NULL REFERENCES users(id),
    destination TEXT NOT NULL,
    basis TEXT NOT NULL,
    purpose TEXT NOT NULL,
    planned_start TEXT NOT NULL,
    planned_end TEXT NOT NULL CHECK (planned_end > planned_start),
    started_at TEXT,
    finished_at TEXT CHECK (finished_at IS NULL OR (started_at IS NOT NULL AND finished_at >= started_at)),
    created_at TEXT NOT NULL
);

CREATE INDEX work_trips_by_company_employee ON work_trips(company_id, employee_id, planned_start);
CREATE UNIQUE INDEX work_trips_one_active ON work_trips(company_id, employee_id)
    WHERE started_at IS NOT NULL AND finished_at IS NULL;

CREATE TABLE work_trip_tasks (
    trip_id BIGINT NOT NULL REFERENCES work_trips(id),
    task_id BIGINT NOT NULL UNIQUE REFERENCES tasks(id),
    PRIMARY KEY (trip_id, task_id)
);

CREATE TABLE employee_work_modes (
    employee_id BIGINT PRIMARY KEY REFERENCES users(id),
    work_mode TEXT NOT NULL CHECK (work_mode IN ('stationary', 'field'))
);
