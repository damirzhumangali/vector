CREATE TABLE contract_payment_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES work_contracts(id),
    payment_index INTEGER NOT NULL CHECK (payment_index BETWEEN 0 AND 60),
    request_id TEXT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 1 AND 1999999999998),
    received_on TEXT NOT NULL,
    created_at TEXT NOT NULL,
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    recorded_by_name TEXT NOT NULL,
    UNIQUE (contract_id, request_id)
);

CREATE INDEX contract_receipts_by_payment
    ON contract_payment_receipts(contract_id, payment_index, received_on, id);
