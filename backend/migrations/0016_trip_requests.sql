CREATE TABLE work_trip_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    destination TEXT NOT NULL,
    purpose TEXT NOT NULL,
    planned_start TEXT NOT NULL,
    planned_end TEXT NOT NULL CHECK (planned_end > planned_start),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'declined')),
    reason TEXT NOT NULL DEFAULT '',
    trip_id BIGINT UNIQUE REFERENCES work_trips(id),
    created_at TEXT NOT NULL,
    decided_at TEXT,
    decided_by BIGINT REFERENCES users(id),
    CHECK ((status = 'approved') = (trip_id IS NOT NULL)),
    CHECK ((status = 'pending') = (decided_at IS NULL)),
    CHECK ((decided_at IS NULL) = (decided_by IS NULL)),
    CHECK (status <> 'declined' OR reason <> '')
);

CREATE INDEX work_trip_requests_by_company_employee
    ON work_trip_requests(company_id, employee_id, status, created_at);

CREATE TABLE work_trip_request_tasks (
    request_id BIGINT NOT NULL REFERENCES work_trip_requests(id),
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    PRIMARY KEY (request_id, task_id)
);
