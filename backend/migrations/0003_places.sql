CREATE TABLE work_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name TEXT NOT NULL,
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius DOUBLE PRECISION NOT NULL CHECK (radius BETWEEN 1 AND 10000)
);

CREATE INDEX work_sites_by_company ON work_sites(company_id, name, id);

ALTER TABLE tasks ADD COLUMN object_id BIGINT REFERENCES work_sites(id);
