CREATE TABLE work_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    number TEXT NOT NULL,
    number_key TEXT NOT NULL,
    signed_on TEXT NOT NULL,
    customer TEXT NOT NULL,
    legal_entity TEXT NOT NULL,
    legal_entity_key TEXT NOT NULL,
    object_ids TEXT NOT NULL,
    installation_amount BIGINT NOT NULL CHECK (installation_amount BETWEEN 0 AND 999999999999),
    support_amount BIGINT NOT NULL CHECK (support_amount BETWEEN 0 AND 999999999999),
    payment_mode TEXT NOT NULL CHECK (payment_mode IN ('combined', 'separate')),
    payments TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active')),
    revision INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1),
    CHECK (installation_amount > 0 OR support_amount > 0),
    UNIQUE (company_id, legal_entity_key, number_key)
);

CREATE INDEX work_contracts_by_company ON work_contracts(company_id, signed_on DESC, id DESC);
