CREATE TABLE task_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    author_id BIGINT NOT NULL REFERENCES users(id),
    author_name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('material', 'before', 'after')),
    caption TEXT NOT NULL,
    created_at TEXT NOT NULL,
    captured_at TEXT NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    accuracy DOUBLE PRECISION,
    sha256 TEXT NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    original_image BYTEA NOT NULL,
    display_image BYTEA NOT NULL,
    rejected_reason TEXT,
    rejected_at TEXT,
    rejected_by BIGINT REFERENCES users(id)
);

CREATE INDEX task_media_task ON task_media(task_id, id);
CREATE UNIQUE INDEX task_media_active_proof ON task_media(task_id, kind)
    WHERE kind IN ('before', 'after') AND rejected_at IS NULL;
