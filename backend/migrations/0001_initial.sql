CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    name TEXT NOT NULL,
    login TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('employee', 'dispatcher', 'manager')),
    is_owner INTEGER NOT NULL DEFAULT 0,
    password_hash BYTEA NOT NULL,
    password_salt BYTEA NOT NULL,
    last_login_at TEXT,
    invite_hash BYTEA,
    invite_expires_at BIGINT,
    invite_required INTEGER NOT NULL DEFAULT 0,
    UNIQUE (company_id, login)
);

CREATE UNIQUE INDEX users_by_invite ON users(invite_hash) WHERE invite_hash IS NOT NULL;

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    expires_at BIGINT NOT NULL
);

CREATE INDEX sessions_by_expiry ON sessions(expires_at);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    assignee_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    object TEXT NOT NULL,
    address TEXT NOT NULL,
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'assigned',
    checks TEXT NOT NULL DEFAULT '[false,false,false,false,false]',
    photo_before INTEGER NOT NULL DEFAULT 0,
    photo_after INTEGER NOT NULL DEFAULT 0,
    rework_reason TEXT NOT NULL DEFAULT '',
    revision INTEGER NOT NULL DEFAULT 1,
    location TEXT,
    deadline TEXT,
    arrival TEXT,
    repeat_of BIGINT REFERENCES tasks(id) DEFERRABLE INITIALLY IMMEDIATE,
    cancel_reason TEXT NOT NULL DEFAULT '',
    result TEXT NOT NULL DEFAULT ''
);

CREATE INDEX tasks_by_company_assignee ON tasks(company_id, assignee_id);
CREATE UNIQUE INDEX task_repeat ON tasks(repeat_of) WHERE repeat_of IS NOT NULL;

CREATE TABLE task_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    status TEXT NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    actor_name TEXT NOT NULL,
    created_at TEXT NOT NULL,
    reason TEXT NOT NULL,
    position TEXT
);

CREATE INDEX events_by_task ON task_events(task_id, id);
