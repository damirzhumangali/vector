CREATE TABLE work_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    object_id BIGINT NOT NULL REFERENCES work_sites(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    start_date TEXT NOT NULL,
    start_time TEXT NOT NULL,
    zone TEXT NOT NULL,
    frequency TEXT NOT NULL CHECK (frequency IN ('once', 'daily', 'weekly', 'monthly')),
    repeat_interval INTEGER NOT NULL,
    horizon_days INTEGER NOT NULL,
    holiday_rule TEXT NOT NULL CHECK (holiday_rule IN ('skip', 'move', 'run')),
    priority INTEGER NOT NULL,
    duration_minutes INTEGER NOT NULL,
    enabled INTEGER NOT NULL,
    generated_through TEXT
);

CREATE INDEX work_plans_by_company ON work_plans(company_id, id);

CREATE TABLE planned_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    object_id BIGINT NOT NULL REFERENCES work_sites(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    scheduled_at TEXT NOT NULL,
    deadline TEXT NOT NULL,
    priority INTEGER NOT NULL,
    task_id BIGINT UNIQUE REFERENCES tasks(id),
    plan_id BIGINT REFERENCES work_plans(id),
    occurrence_date TEXT,
    UNIQUE (plan_id, occurrence_date)
);

CREATE INDEX planned_jobs_by_company ON planned_jobs(company_id, scheduled_at, id);
CREATE INDEX planned_jobs_due ON planned_jobs(company_id, scheduled_at) WHERE task_id IS NULL;
