CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id),
    employee_id BIGINT NOT NULL REFERENCES users(id),
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    task_id BIGINT REFERENCES tasks(id),
    kind TEXT NOT NULL CHECK (kind IN ('urgent_leave', 'lateness', 'emergency')),
    status TEXT NOT NULL DEFAULT 'open',
    reason TEXT NOT NULL,
    safe INTEGER CHECK (safe IS NULL OR safe IN (0, 1)),
    minutes INTEGER,
    event_uuid TEXT,
    occurred_at TEXT NOT NULL,
    created_at TEXT NOT NULL,
    decision_reason TEXT,
    decided_at TEXT,
    decided_by BIGINT REFERENCES users(id),
    UNIQUE (company_id, employee_id, event_uuid)
);
CREATE INDEX incidents_company_recent ON incidents(company_id, id);
CREATE UNIQUE INDEX incidents_open_leave ON incidents(company_id, employee_id)
    WHERE kind = 'urgent_leave' AND status = 'open';
CREATE UNIQUE INDEX incidents_open_emergency ON incidents(company_id, task_id)
    WHERE kind = 'emergency' AND status = 'open';
CREATE TABLE incident_tasks (
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    original_status TEXT NOT NULL,
    transferred_to BIGINT REFERENCES users(id),
    PRIMARY KEY (incident_id, task_id)
);
