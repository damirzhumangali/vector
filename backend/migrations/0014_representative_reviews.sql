CREATE TABLE task_representative_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id),
    report_event_id BIGINT NOT NULL REFERENCES task_events(id),
    issued_by BIGINT NOT NULL REFERENCES users(id),
    token_hash BYTEA UNIQUE,
    expires_at BIGINT NOT NULL,
    decision TEXT CHECK (decision IN ('confirmed', 'remark')),
    method TEXT NOT NULL DEFAULT 'link',
    representative_name TEXT NOT NULL DEFAULT '',
    reason TEXT NOT NULL DEFAULT '',
    comment TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    decided_at TEXT,
    photo BYTEA,
    UNIQUE (task_id, report_event_id)
);
